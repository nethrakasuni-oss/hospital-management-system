
BEGIN;

-- ADMIN receives every permission
INSERT INTO "RolePermission"
("roleId", "permissionId", "createdAt")
SELECT r.id, p.id, NOW()
FROM "Role" r
CROSS JOIN "Permission" p
WHERE r.name = 'ADMIN'
ON CONFLICT ("roleId", "permissionId") DO NOTHING;


